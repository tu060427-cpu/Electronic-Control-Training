/** 
 *@brief 配置过滤器
*/ 
void can_filter(void)
{
  CAN_FilterTypeDef filter;
  filter.FilterMode = CAN_FILTERMODE_IDMASK;
  filter.FilterScale = CAN_FILTERSCALE_32BIT;
  filter.FilterFIFOAssignment = CAN_FilterFIFO0;

  filter.FilterBank = 0;

  filter.FilterIdHigh = 0x001 << 5;
  filter.FilterIdLow = 0;
  filter.FilterMaskIdHigh = 0x7FF << 5;
  filter.FilterMaskIdLow = 0;

  filter.SlaveStartFilterBank = 0;

  filter.FilterActivation = ENABLE;

  HAL_CAN_ConfigFilter(&hcan,&filter);

}

/**
  *@brief 发送配置
  *@brief Txdata:8个数据的数组地址
*/
void can_send(uint8_t *Txdata)  
{
  uint32_t TxMailbox;


  CAN_TxHeaderTypeDef TxHeader;
  TxHeader.StdId = 0x001;
  TxHeader.ExtId = 0;
  TxHeader.IDE = CAN_ID_STD;
  TxHeader.RTR = CAN_RTR_DATA;
  TxHeader.DLC = 8;
  TxHeader.TransmitGlobalTime = DISABLE;

  HAL_CAN_AddTxMessage(&hcan,&TxHeader,Txdata,&TxMailbox);
}


/**
  *@brief 接收配置
  *@brief RXdata:8个数据的数组地址
*/
void  can_read(uint8_t *Rxdata)
{
  CAN_RxHeaderTypeDef RXHeader;
  uint8_t data[8];
  uint8_t i;
  if(HAL_CAN_GetRxMessage(&hcan,CAN_RX_FIFO0,&RXHeader,data) == HAL_OK)
  {
    if(RXHeader.StdId == 0x001)
    {
      for(i = 0;i < 8;i++)
      {
        Rxdata[i] = data[i];
      }
    }
  }

}
